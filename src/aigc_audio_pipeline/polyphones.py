def apply_business_english_drama_polyphone_overrides(text: str) -> str:
    """Return phonetic `tts_text` override for modern bilingual business-drama Mandarin lines."""
    if not text:
        return text
    out = text
    for canonical, phonetic in BUSINESS_ENGLISH_DRAMA_POLYPHONE_MAP:
        if canonical in out:
            out = out.replace(canonical, phonetic)
    for pattern, phonetic in _BUSINESS_DRAMA_CONTEXT_REGEXES:
        out = pattern.sub(phonetic, out)
    return out


